// chartDeployment renders the chart of helm/<name>, with the values of its
// values.yaml changed by setValues. Every rendered document must decode as
// YAML, as helm template requires. It returns the Deployment, decoded with
// no unknown field.
func chartDeployment(t *testing.T, name string, setValues func(values map[string]interface{})) *appsv1.Deployment {
	t.Helper()
	dir := filepath.Join("..", "..", "..", "helm", name)
	raw, err := os.ReadFile(filepath.Join(dir, "values.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	values := map[string]interface{}{}
	if err := yaml.Unmarshal(raw, &values); err != nil {
		t.Fatal(err)
	}
	setValues(values)
	// Chart.yaml is generated by the Makefile: the metadata is set here
	ch := &chart.Chart{
		Metadata: &chart.Metadata{APIVersion: "v2", Name: name, Version: "0.0.0", AppVersion: "v0.0.0",
			Annotations: map[string]string{"kubotal_image_repository": "registry.local/kubocd"}},
		Values: values,
	}
	entries, err := os.ReadDir(filepath.Join(dir, "templates"))
	if err != nil {
		t.Fatal(err)
	}
	for _, entry := range entries {
		data, err := os.ReadFile(filepath.Join(dir, "templates", entry.Name()))
		if err != nil {
			t.Fatal(err)
		}
		ch.Templates = append(ch.Templates, &common.File{Name: "templates/" + entry.Name(), Data: data})
	}
	renderValues, err := util.ToRenderValues(ch, nil, common.ReleaseOptions{Name: name, Namespace: "kubocd"}, nil)
	if err != nil {
		t.Fatal(err)
	}
	rendered, err := engine.Render(ch, renderValues)
	if err != nil {
		t.Fatal(err)
	}
	for file, content := range rendered {
		for _, document := range releaseutil.SplitManifests(content) {
			if err := yaml.Unmarshal([]byte(document), &map[string]interface{}{}); err != nil {
				t.Fatalf("%s is not valid YAML: %v\n%s", file, err, document)
			}
		}
	}
	deployment := &appsv1.Deployment{}
	if err := yaml.UnmarshalStrict([]byte(rendered[name+"/templates/deployment.yaml"]), deployment); err != nil {
		t.Fatalf("the Deployment does not decode: %v", err)
	}
	if len(deployment.Spec.Template.Spec.Containers) == 0 {
		t.Fatal("the Deployment has no container")
	}
	return deployment
}

// extraEnv has a plain value and a value read from a Secret.
func extraEnv() []interface{} {
	return []interface{}{
		map[string]interface{}{"name": "EXTRA_PLAIN", "value": "plain"},
		map[string]interface{}{"name": "EXTRA_FROM_SECRET", "valueFrom": map[string]interface{}{
			"secretKeyRef": map[string]interface{}{"name": "extra-secret", "key": "token"}}},
	}
}

// extraVolumes are two persistent volume claims.
func extraVolumes() []interface{} {
	return []interface{}{
		map[string]interface{}{"name": "extra-data", "mountPath": "/extra/data", "claimName": "extra-data-pvc"},
		map[string]interface{}{"name": "extra-cache", "mountPath": "/extra/cache", "claimName": "extra-cache-pvc"},
	}
}

func envNames(env []corev1.EnvVar) []string {
	names := make([]string, 0, len(env))
	for _, variable := range env {
		names = append(names, variable.Name)
	}
	return names
}

func mountsOf(container corev1.Container) []string {
	mounts := make([]string, 0, len(container.VolumeMounts))
	for _, mount := range container.VolumeMounts {
		mounts = append(mounts, mount.Name+"="+mount.MountPath)
	}
	return mounts
}

func volumeNames(volumes []corev1.Volume) []string {
	names := make([]string, 0, len(volumes))
	for _, volume := range volumes {
		names = append(names, volume.Name)
	}
	return names
}

func claimsOf(volumes []corev1.Volume) []string {
	claims := make([]string, 0)
	for _, volume := range volumes {
		if volume.PersistentVolumeClaim != nil {
			claims = append(claims, volume.Name+"="+volume.PersistentVolumeClaim.ClaimName)
		}
	}
	return claims
}

func TestChartsRenderTheirExtraEnvAndVolumes(t *testing.T) {
	sections := map[string]string{"kubocd-ctrl": "controller", "kubocd-wh": "webhook"}
	scenarios := map[string]struct{ env, volumes bool }{
		"defaults": {}, "extraEnv": {env: true}, "extraVolumes": {volumes: true}, "both": {env: true, volumes: true},
	}
	for name, section := range sections {
		defaults := chartDeployment(t, name, func(map[string]interface{}) {})
		base := defaults.Spec.Template.Spec.Containers[0]
		if got, want := envNames(base.Env), []string{"MY_POD_NAME", "MY_POD_NAMESPACE"}; !slices.Equal(got, want) {
			t.Fatalf("%s: got the default env %v, want %v", name, got, want)
		}
		for scenario, extra := range scenarios {
			t.Run(fmt.Sprintf("%s %s", name, scenario), func(t *testing.T) {
				deployment := chartDeployment(t, name, func(values map[string]interface{}) {
					if extra.env {
						values[section].(map[string]interface{})["extraEnv"] = extraEnv()
					}
					if extra.volumes {
						values[section].(map[string]interface{})["extraVolumes"] = extraVolumes()
					}
				})
				pod := deployment.Spec.Template.Spec
				container := pod.Containers[0]
				wantEnv, wantMounts := envNames(base.Env), mountsOf(base)
				wantVolumes, wantClaims := volumeNames(defaults.Spec.Template.Spec.Volumes), []string{}
				if extra.env {
					wantEnv = append([]string{"EXTRA_PLAIN", "EXTRA_FROM_SECRET"}, wantEnv...)
				}
				if extra.volumes {
					wantMounts = append(wantMounts, "extra-data=/extra/data", "extra-cache=/extra/cache")
					wantVolumes = append(wantVolumes, "extra-data", "extra-cache")
					wantClaims = []string{"extra-data=extra-data-pvc", "extra-cache=extra-cache-pvc"}
				}
				if got := envNames(container.Env); !slices.Equal(got, wantEnv) {
					t.Errorf("got env %v, want %v", got, wantEnv)
				}
				if extra.env {
					fromSecret := &corev1.EnvVarSource{SecretKeyRef: &corev1.SecretKeySelector{
						LocalObjectReference: corev1.LocalObjectReference{Name: "extra-secret"}, Key: "token"}}
					if container.Env[0].Value != "plain" || !reflect.DeepEqual(container.Env[1].ValueFrom, fromSecret) {
						t.Errorf("got env %+v, want EXTRA_PLAIN=plain and EXTRA_FROM_SECRET from the Secret", container.Env[:2])
					}
				}
				if got := mountsOf(container); !slices.Equal(got, wantMounts) {
					t.Errorf("got mounts %v, want %v", got, wantMounts)
				}
				if got := volumeNames(pod.Volumes); !slices.Equal(got, wantVolumes) {
					t.Errorf("got volumes %v, want %v", got, wantVolumes)
				}
				if got := claimsOf(pod.Volumes); !slices.Equal(got, wantClaims) {
					t.Errorf("got claims %v, want %v", got, wantClaims)
				}
				for _, mount := range container.VolumeMounts {
					if !slices.Contains(volumeNames(pod.Volumes), mount.Name) {
						t.Errorf("the mount %s=%s has no volume", mount.Name, mount.MountPath)
					}
				}
			})
		}
	}
}

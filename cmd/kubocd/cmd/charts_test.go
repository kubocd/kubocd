// renderChart renders the chart of helm/<name> as the release of that name,
// in the namespace kubocd, as renderRelease does.
func renderChart(t *testing.T, name string, setValues func(values map[string]interface{})) map[string]string {
	t.Helper()
	return renderRelease(t, name, name, "kubocd", setValues)
}

// renderRelease renders the chart of helm/<name> as the release given, in the
// namespace given, with the values of its values.yaml changed by setValues.
// Every rendered document must decode as YAML, as helm template requires. It
// returns the documents by kind and name, such as
// Deployment/kubocd-ctrl-controller.
func renderRelease(t *testing.T, name string, release string, namespace string,
	setValues func(values map[string]interface{})) map[string]string {
	t.Helper()
	dir := filepath.Join("..", "..", "..", "helm", name)
	raw, err := os.ReadFile(filepath.Join(dir, "values.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	values := map[string]interface{}{}
	if err := yaml.Unmarshal(raw, &values); err != nil {
		t.Fatal(err)
	}
	setValues(values)
	// Chart.yaml is generated by the Makefile: the metadata is set here
	ch := &chart.Chart{
		Metadata: &chart.Metadata{APIVersion: "v2", Name: name, Version: "0.0.0", AppVersion: "v0.0.0",
			Annotations: map[string]string{"kubotal_image_repository": "registry.local/kubocd"}},
		Values: values,
	}
	entries, err := os.ReadDir(filepath.Join(dir, "templates"))
	if err != nil {
		t.Fatal(err)
	}
	for _, entry := range entries {
		data, err := os.ReadFile(filepath.Join(dir, "templates", entry.Name()))
		if err != nil {
			t.Fatal(err)
		}
		ch.Templates = append(ch.Templates, &common.File{Name: "templates/" + entry.Name(), Data: data})
	}
	renderValues, err := util.ToRenderValues(ch, nil, common.ReleaseOptions{Name: release, Namespace: namespace}, nil)
	if err != nil {
		t.Fatal(err)
	}
	rendered, err := engine.Render(ch, renderValues)
	if err != nil {
		t.Fatal(err)
	}
	documents := map[string]string{}
	for file, content := range rendered {
		for _, document := range releaseutil.SplitManifests(content) {
			object := struct {
				Kind     string `json:"kind"`
				Metadata struct {
					Name string `json:"name"`
				} `json:"metadata"`
			}{}
			if err := yaml.Unmarshal([]byte(document), &object); err != nil {
				t.Fatalf("%s is not valid YAML: %v\n%s", file, err, document)
			}
			if object.Kind == "" {
				continue
			}
			key := object.Kind + "/" + object.Metadata.Name
			if _, ok := documents[key]; ok {
				t.Fatalf("%s is rendered twice", key)
			}
			documents[key] = document
		}
	}
	return documents
}

// decodeStrict decodes the rendered document of kind and name into object,
// with no unknown field.
func decodeStrict(t *testing.T, documents map[string]string, kind string, name string, object interface{}) {
	t.Helper()
	document, ok := documents[kind+"/"+name]
	if !ok {
		t.Fatalf("no %s/%s rendered, got %v", kind, name, slices.Sorted(maps.Keys(documents)))
	}
	if err := yaml.UnmarshalStrict([]byte(document), object); err != nil {
		t.Fatalf("%s/%s does not decode: %v", kind, name, err)
	}
}

// chartDeployment renders the chart of helm/<name> in the namespace kubocd, as
// renderChart does. It returns its Deployment.
func chartDeployment(t *testing.T, name string, setValues func(values map[string]interface{})) *appsv1.Deployment {
	t.Helper()
	return deploymentOf(t, renderChart(t, name, setValues))
}

// deploymentOf returns the only Deployment of a render.
func deploymentOf(t *testing.T, documents map[string]string) *appsv1.Deployment {
	t.Helper()
	names := make([]string, 0)
	for key := range documents {
		if kind, name, _ := strings.Cut(key, "/"); kind == "Deployment" {
			names = append(names, name)
		}
	}
	if len(names) != 1 {
		t.Fatalf("got the Deployments %v, want one", names)
	}
	deployment := &appsv1.Deployment{}
	decodeStrict(t, documents, "Deployment", names[0], deployment)
	if len(deployment.Spec.Template.Spec.Containers) == 0 {
		t.Fatal("the Deployment has no container")
	}
	return deployment
}

// extraEnv has a plain value and a value read from a Secret.
func extraEnv() []interface{} {
	return []interface{}{
		map[string]interface{}{"name": "EXTRA_PLAIN", "value": "plain"},
		map[string]interface{}{"name": "EXTRA_FROM_SECRET", "valueFrom": map[string]interface{}{
			"secretKeyRef": map[string]interface{}{"name": "extra-secret", "key": "token"}}},
	}
}

// extraVolumes are two persistent volume claims.
func extraVolumes() []interface{} {
	return []interface{}{
		map[string]interface{}{"name": "extra-data", "mountPath": "/extra/data", "claimName": "extra-data-pvc"},
		map[string]interface{}{"name": "extra-cache", "mountPath": "/extra/cache", "claimName": "extra-cache-pvc"},
	}
}

func envNames(env []corev1.EnvVar) []string {
	names := make([]string, 0, len(env))
	for _, variable := range env {
		names = append(names, variable.Name)
	}
	return names
}

func mountsOf(container corev1.Container) []string {
	mounts := make([]string, 0, len(container.VolumeMounts))
	for _, mount := range container.VolumeMounts {
		mounts = append(mounts, mount.Name+"="+mount.MountPath)
	}
	return mounts
}

func volumeNames(volumes []corev1.Volume) []string {
	names := make([]string, 0, len(volumes))
	for _, volume := range volumes {
		names = append(names, volume.Name)
	}
	return names
}

func claimsOf(volumes []corev1.Volume) []string {
	claims := make([]string, 0)
	for _, volume := range volumes {
		if volume.PersistentVolumeClaim != nil {
			claims = append(claims, volume.Name+"="+volume.PersistentVolumeClaim.ClaimName)
		}
	}
	return claims
}

func TestChartsRenderTheirExtraEnvAndVolumes(t *testing.T) {
	sections := map[string]string{"kubocd-ctrl": "controller", "kubocd-wh": "webhook"}
	scenarios := map[string]struct{ env, volumes bool }{
		"defaults": {}, "extraEnv": {env: true}, "extraVolumes": {volumes: true}, "both": {env: true, volumes: true},
	}
	for name, section := range sections {
		defaults := chartDeployment(t, name, func(map[string]interface{}) {})
		base := defaults.Spec.Template.Spec.Containers[0]
		if got, want := envNames(base.Env), []string{"MY_POD_NAME", "MY_POD_NAMESPACE"}; !slices.Equal(got, want) {
			t.Fatalf("%s: got the default env %v, want %v", name, got, want)
		}
		for scenario, extra := range scenarios {
			t.Run(fmt.Sprintf("%s %s", name, scenario), func(t *testing.T) {
				deployment := chartDeployment(t, name, func(values map[string]interface{}) {
					if extra.env {
						values[section].(map[string]interface{})["extraEnv"] = extraEnv()
					}
					if extra.volumes {
						values[section].(map[string]interface{})["extraVolumes"] = extraVolumes()
					}
				})
				pod := deployment.Spec.Template.Spec
				container := pod.Containers[0]
				wantEnv, wantMounts := envNames(base.Env), mountsOf(base)
				wantVolumes, wantClaims := volumeNames(defaults.Spec.Template.Spec.Volumes), []string{}
				if extra.env {
					wantEnv = append([]string{"EXTRA_PLAIN", "EXTRA_FROM_SECRET"}, wantEnv...)
				}
				if extra.volumes {
					wantMounts = append(wantMounts, "extra-data=/extra/data", "extra-cache=/extra/cache")
					wantVolumes = append(wantVolumes, "extra-data", "extra-cache")
					wantClaims = []string{"extra-data=extra-data-pvc", "extra-cache=extra-cache-pvc"}
				}
				if got := envNames(container.Env); !slices.Equal(got, wantEnv) {
					t.Errorf("got env %v, want %v", got, wantEnv)
				}
				if extra.env {
					fromSecret := &corev1.EnvVarSource{SecretKeyRef: &corev1.SecretKeySelector{
						LocalObjectReference: corev1.LocalObjectReference{Name: "extra-secret"}, Key: "token"}}
					if container.Env[0].Value != "plain" || !reflect.DeepEqual(container.Env[1].ValueFrom, fromSecret) {
						t.Errorf("got env %+v, want EXTRA_PLAIN=plain and EXTRA_FROM_SECRET from the Secret", container.Env[:2])
					}
				}
				if got := mountsOf(container); !slices.Equal(got, wantMounts) {
					t.Errorf("got mounts %v, want %v", got, wantMounts)
				}
				if got := volumeNames(pod.Volumes); !slices.Equal(got, wantVolumes) {
					t.Errorf("got volumes %v, want %v", got, wantVolumes)
				}
				if got := claimsOf(pod.Volumes); !slices.Equal(got, wantClaims) {
					t.Errorf("got claims %v, want %v", got, wantClaims)
				}
				for _, mount := range container.VolumeMounts {
					if !slices.Contains(volumeNames(pod.Volumes), mount.Name) {
						t.Errorf("the mount %s=%s has no volume", mount.Name, mount.MountPath)
					}
				}
			})
		}
	}
}

// networkPolicies returns the NetworkPolicies of a render, by namespace and
// name.
func networkPolicies(t *testing.T, documents map[string]string) map[string]networkingv1.NetworkPolicy {
	t.Helper()
	policies := map[string]networkingv1.NetworkPolicy{}
	for key := range documents {
		if kind, name, _ := strings.Cut(key, "/"); kind == "NetworkPolicy" {
			policy := networkingv1.NetworkPolicy{}
			decodeStrict(t, documents, kind, name, &policy)
			policies[policy.Namespace+"/"+policy.Name] = policy
		}
	}
	return policies
}

// tcpPorts are NetworkPolicy ports, TCP.
func tcpPorts(ports ...int32) []networkingv1.NetworkPolicyPort {
	tcp := corev1.ProtocolTCP
	policyPorts := make([]networkingv1.NetworkPolicyPort, 0, len(ports))
	for _, port := range ports {
		number := intstr.FromInt32(port)
		policyPorts = append(policyPorts, networkingv1.NetworkPolicyPort{Protocol: &tcp, Port: &number})
	}
	return policyPorts
}

// mustEqualSpec fails the test unless the spec of the policy is want, and
// prints both as YAML.
func mustEqualSpec(t *testing.T, policy networkingv1.NetworkPolicy, want networkingv1.NetworkPolicySpec) {
	t.Helper()
	if !reflect.DeepEqual(policy.Spec, want) {
		got, _ := yaml.Marshal(policy.Spec)
		expected, _ := yaml.Marshal(want)
		t.Fatalf("NetworkPolicy %s/%s, got the spec\n%s\nwant\n%s", policy.Namespace, policy.Name, got, expected)
	}
}

// chartValues sets a value of a section of values.yaml.
func chartValues(section string, key string, value interface{}) func(values map[string]interface{}) {
	return func(values map[string]interface{}) {
		values[section].(map[string]interface{})[key] = value
	}
}

// noChange leaves the values of values.yaml as they are.
func noChange(map[string]interface{}) {}

// namespaceNamed selects the namespace of that name.
func namespaceNamed(name string) *metav1.LabelSelector {
	return &metav1.LabelSelector{MatchLabels: map[string]string{"kubernetes.io/metadata.name": name}}
}

// policyInstalls are the releases and namespaces of the chart that the policy
// tests render, so that a release or a namespace written in a template fails.
var policyInstalls = []struct{ release, namespace string }{{"kubocd-ctrl", "kubocd"}, {"kcd", "kcd-system"}}

// policiesIn returns the names of the NetworkPolicies of a namespace.
func policiesIn(policies map[string]networkingv1.NetworkPolicy, namespace string) []string {
	names := make([]string, 0)
	for _, policy := range policies {
		if policy.Namespace == namespace {
			names = append(names, policy.Name)
		}
	}
	slices.Sort(names)
	return names
}

func TestTheChartLetsOnlyTheControllerAndFluxReachSourceController(t *testing.T) {
	cases := map[string]struct {
		values        func(values map[string]interface{})
		fluxNamespace string
	}{
		"defaults":               {noChange, "flux-system"},
		"another Flux namespace": {chartValues("networkPolicies", "fluxNamespace", "flux"), "flux"},
		"another base name":      {chartValues("controller", "baseNameOverride", "other"), "flux-system"},
	}
	for _, install := range policyInstalls {
		for name, c := range cases {
			namespace := install.namespace
			t.Run(install.release+" in "+namespace+", "+name, func(t *testing.T) {
				documents := renderRelease(t, "kubocd-ctrl", install.release, namespace, c.values)
				controller := deploymentOf(t, documents).Spec.Selector.MatchLabels
				policies := networkPolicies(t, documents)
				if got := policiesIn(policies, c.fluxNamespace); !slices.Equal(got, []string{"kubocd-allow-sources-fetch"}) {
					t.Fatalf("got the NetworkPolicies %v in %s, want kubocd-allow-sources-fetch only", got, c.fluxNamespace)
				}
				mustEqualSpec(t, policies[c.fluxNamespace+"/kubocd-allow-sources-fetch"], networkingv1.NetworkPolicySpec{
					PodSelector: metav1.LabelSelector{MatchLabels: map[string]string{"app": "source-controller"}},
					Ingress: []networkingv1.NetworkPolicyIngressRule{{
						From: []networkingv1.NetworkPolicyPeer{
							{PodSelector: &metav1.LabelSelector{}},
							{NamespaceSelector: namespaceNamed(namespace), PodSelector: &metav1.LabelSelector{MatchLabels: controller}},
						},
						Ports: tcpPorts(9090),
					}},
					PolicyTypes: []networkingv1.PolicyType{networkingv1.PolicyTypeIngress},
				})
			})
		}
	}
	t.Run("disabled", func(t *testing.T) {
		disabled := chartValues("networkPolicies", "enabled", false)
		policies := networkPolicies(t, renderChart(t, "kubocd-ctrl", disabled))
		if len(policies) != 0 {
			t.Fatalf("got the NetworkPolicies %v, want none", slices.Sorted(maps.Keys(policies)))
		}
	})
}

// chartServerPolicy is the NetworkPolicy of the chart server, with the
// default base name.
const chartServerPolicy = "kubocd-ctrl-controller-helm-repository"

func TestTheChartLetsOnlySourceControllerReachTheChartServer(t *testing.T) {
	withMetrics := func(secured bool) func(values map[string]interface{}) {
		return func(values map[string]interface{}) {
			metrics := values["controller"].(map[string]interface{})["metrics"].(map[string]interface{})
			metrics["enabled"] = true
			metrics["secured"] = secured
		}
	}
	otherFlux := chartValues("networkPolicies", "fluxNamespace", "flux")
	otherBase := chartValues("controller", "baseNameOverride", "other")
	// base is the base name of the controller resources, the release name
	// followed by -controller when empty
	cases := map[string]struct {
		values        func(values map[string]interface{})
		base          string
		fluxNamespace string
		metrics       bool
	}{
		"defaults":               {noChange, "", "flux-system", false},
		"metrics":                {withMetrics(false), "", "flux-system", true},
		"secured metrics":        {withMetrics(true), "", "flux-system", true},
		"another Flux namespace": {otherFlux, "", "flux", false},
		"another base name":      {otherBase, "other", "flux-system", false},
	}
	for _, install := range policyInstalls {
		for name, c := range cases {
			namespace := install.namespace
			t.Run(install.release+" in "+namespace+", "+name, func(t *testing.T) {
				documents := renderRelease(t, "kubocd-ctrl", install.release, namespace, c.values)
				controller := deploymentOf(t, documents).Spec.Selector.MatchLabels
				policies := networkPolicies(t, documents)
				base := c.base
				if base == "" {
					base = install.release + "-controller"
				}
				if got := policiesIn(policies, namespace); !slices.Equal(got, []string{base + "-helm-repository"}) {
					t.Fatalf("got the NetworkPolicies %v in %s, want %s-helm-repository only", got, namespace, base)
				}
				policy := policies[namespace+"/"+base+"-helm-repository"]
				rules := []networkingv1.NetworkPolicyIngressRule{{
					From: []networkingv1.NetworkPolicyPeer{{
						NamespaceSelector: namespaceNamed(c.fluxNamespace),
						PodSelector:       &metav1.LabelSelector{MatchLabels: map[string]string{"app": "source-controller"}},
					}},
					Ports: tcpPorts(9090),
				}}
				if c.metrics {
					rules = append(rules, networkingv1.NetworkPolicyIngressRule{Ports: tcpPorts(8443)})
				}
				mustEqualSpec(t, policy, networkingv1.NetworkPolicySpec{
					PodSelector: metav1.LabelSelector{MatchLabels: controller},
					Ingress:     rules,
					PolicyTypes: []networkingv1.PolicyType{networkingv1.PolicyTypeIngress},
				})
			})
		}
	}
	for name, values := range map[string]func(values map[string]interface{}){
		"policies disabled":  chartValues("networkPolicies", "enabled", false),
		"controller outside": chartValues("controller", "enabled", false),
	} {
		t.Run(name, func(t *testing.T) {
			policies := networkPolicies(t, renderChart(t, "kubocd-ctrl", values))
			if _, ok := policies["kubocd/"+chartServerPolicy]; ok {
				t.Fatalf("got the NetworkPolicies %v, want none in kubocd", slices.Sorted(maps.Keys(policies)))
			}
		})
	}
}
